/// How long an instance lasts (RFC 5545, Section 3.3.6): a number of nominal
/// days, which keep the wall time across daylight saving changes, then an
/// exact time.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Length {
    pub(crate) days: i64,
    pub(crate) time: SignedDuration,
}

impl Length {
    pub(crate) const ZERO: Length = Length {
        days: 0,
        time: SignedDuration::ZERO,
    };
    pub(crate) const ONE_DAY: Length = Length {
        days: 1,
        time: SignedDuration::ZERO,
    };

    /// An exact length, as from a DATE-TIME DTSTART to its DTEND.
    pub(crate) fn exact(time: SignedDuration) -> Self {
        Length { days: 0, time }
    }

    /// A DURATION value: its weeks and days are nominal, its hours,
    /// minutes and seconds exact.
    pub(crate) fn of(duration: &super::ICalendarDuration) -> Self {
        let sign = if duration.neg { -1 } else { 1 };
        Length {
            days: sign * (i64::from(duration.weeks) * 7 + i64::from(duration.days)),
            time: SignedDuration::from_secs(
                sign * (i64::from(duration.hours) * 3600
                    + i64::from(duration.minutes) * 60
                    + i64::from(duration.seconds)),
            ),
        }
    }

    /// The length between two DATE values: whole nominal days.
    pub(crate) fn between_dates(start: jiff::civil::DateTime, end: jiff::civil::DateTime) -> Self {
        let span = start.duration_until(end);
        Length {
            days: span.as_secs().div_euclid(86_400),
            time: SignedDuration::from_secs(span.as_secs().rem_euclid(86_400)),
        }
    }

    /// The end of an instance that starts at `start`: the nominal days are
    /// added on the calendar, then the exact time.
    pub(crate) fn end_of(&self, start: &Zoned) -> Option<Zoned> {
        let after_days = if self.days == 0 {
            start.clone()
        } else {
            start
                .checked_add(jiff::Span::new().try_days(self.days).ok()?)
                .ok()?
        };
        after_days.checked_add(self.time).ok()
    }
}

#[allow(clippy::type_complexity)]
#[derive(Debug, Default, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
pub struct CalendarExpand {
    pub events: Vec<CalendarEvent<Zoned, TimeOrDelta<Zoned, SignedDuration>>>,
    pub errors: Vec<CalendarError>,
}

/// One instance of a component.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
#[non_exhaustive]
pub struct CalendarEvent<S, E> {
    /// The component the instance's properties come from: the main component
    /// for a generated instance, or the override component for an overridden
    /// one.
    pub comp_id: u32,
    /// The main component of the recurring series the instance belongs to,
    /// or `None` for a component that does not recur.
    pub series_comp_id: Option<u32>,
    /// The recurrence id of the instance (RFC 5545, Section 3.8.4.4): the
    /// `RECURRENCE-ID` of an override, or the date-time generated by
    /// `DTSTART`, `RRULE` or `RDATE`. `None` for a component that does not
    /// recur.
    pub recurrence_id: Option<S>,
    pub start: S,
    pub end: E,
}

impl<S, E> CalendarEvent<S, E> {
    /// An instance of a component that does not recur.
    pub fn new(comp_id: u32, start: S, end: E) -> Self {
        CalendarEvent {
            comp_id,
            series_comp_id: None,
            recurrence_id: None,
            start,
            end,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[cfg_attr(feature = "serde", serde(tag = "type", content = "data"))]
pub enum TimeOrDelta<T, D> {
    /// A point in time. Expansion always gives an instance's end in this form,
    /// computed with nominal days and exact hours, minutes and seconds (RFC
    /// 5545, Section 3.3.6).
    Time(T),
    /// An exact duration, which cannot express a nominal day across a
    /// daylight saving change.
    Delta(D),
}

#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
pub struct CalendarError {
    pub comp_id: u32,
    pub error: CalendarErrorType,
}

#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
pub enum CalendarErrorType {
    MissingDtStart,
    InvalidDtStart,
    InvalidDtEnd,
    InvalidDuration,
    RRule(RRuleError),
}

impl ICalendar {
    /// Expands every component into its instances, up to `limit` instances
    /// of recurring components in total.
    ///
    /// The same as [`ICalendar::expand_dates_between`] with an unbounded
    /// time range.
    pub fn expand_dates(&self, default_tz: impl Into<Tz>, limit: usize) -> CalendarExpand {
        self.expand_dates_between(default_tz, Timestamp::MIN, Timestamp::MAX, limit)
    }

    /// Expands every component into the instances that overlap the time
    /// range from `start` (inclusive) to `end` (exclusive).
    ///
    /// An instance overlaps the range under the rules of RFC 4791, Section
    /// 9.9 for its component type, so a zero-length instance at `start` is
    /// included. Each recurrence rule stops once its instances pass `end`, so
    /// rules without `COUNT` or `UNTIL` finish without reaching `limit`. An
    /// overridden instance is placed by the override's start: an override
    /// that moves an instance into the range adds it, and one that moves it
    /// out removes it.
    ///
    /// `limit` caps the number of instances generated by recurrence rules,
    /// in total across all components, as a guard against runaway expansion.
    pub fn expand_dates_between(
        &self,
        default_tz: impl Into<Tz>,
        start: Timestamp,
        end: Timestamp,
        mut limit: usize,
    ) -> CalendarExpand {
        let window = Window { start, end };
        let tz_resolver = self.build_tz_resolver().with_default(default_tz);
        let mut expand = CalendarExpand::default();
        let mut recurring = Vec::new();
        // Overrides by series UID and the instant of the instance they
        // replace: RECURRENCE-ID is "the time when the original recurrence
        // instance would occur" (RFC 5545, Section 3.8.4.4), in any time zone.
        let mut overridden = AHashMap::new();
        // The main component of each recurring series, by UID.
        let mut series = AHashMap::new();

        for (comp_id, comp) in self.components.iter().enumerate() {
            if comp.component_type.has_time_ranges() {
                match comp.build_calendar_date(comp_id as u32, &tz_resolver) {
                    Ok(Some(event)) => {
                        if event.rrule.is_some()
                            || (event.rid.is_none() && !event.rdates.is_empty())
                        {
                            series.insert(event.uid, comp_id as u32);
                            recurring.push((comp_id as u32, event));
                        } else if let Some(rid) = &event.rid {
                            overridden
                                .insert((event.uid, rid.timestamp()), (comp_id as u32, event));
                        } else if let Some(cal_event) = event.event
                            && window.contains(&cal_event, event.overlap)
                        {
                            expand.events.push(cal_event);
                        }
                    }
                    Ok(None) => {}
                    Err(error) => {
                        expand.errors.push(CalendarError {
                            comp_id: comp_id as u32,
                            error,
                        });
                    }
                }
            }
        }

        // Expand each recurrence set: DTSTART, RRULE and RDATE instances,
        // minus EXDATE (RFC 5545, Section 3.8.5).
        for (series_comp_id, mut event) in recurring {
            let mut comp_id = series_comp_id;
            let first = event.event.take();
            let rule = match event.rrule.take() {
                Some(mut rrule) => {
                    if event.dt_start.offset.is_none() && event.dt_start_tzid.is_none() {
                        rrule.float_until();
                    }
                    match rule_instances(rrule, event.dt_start.date_time, event.start_tz) {
                        Ok(instances) => Some(instances),
                        Err(error) => {
                            // The rule is unusable; DTSTART and RDATE still define
                            // instances.
                            expand.errors.push(CalendarError { comp_id, error });
                            None
                        }
                    }
                }
                None => None,
            };
            // Without a rule, DTSTART is the first instance; it keeps its own
            // end (DTEND, DURATION or the default).
            let rule: Box<dyn Iterator<Item = Candidate>> = match (rule, first) {
                (Some(rule), _) => Box::new(rule),
                (None, Some(first)) => Box::new(std::iter::once(Candidate {
                    start: first.start,
                    local: None,
                    end: Some(first.end),
                })),
                (None, None) => Box::new(std::iter::empty()),
            };
            let candidates = Merge {
                a: rule.peekable(),
                b: std::mem::take(&mut event.rdates)
                    .into_iter()
                    .map(|(start, end)| Candidate {
                        start,
                        local: None,
                        end,
                    })
                    .peekable(),
            };

            let exdates = event
                .exdates
                .iter()
                .filter_map(|(tz_id, dt)| {
                    dt.to_date_time_with_tz(
                        tz_resolver.resolve_or_default(tz_id.or(event.dt_start_tzid)),
                    )
                })
                .map(|dt| dt.timestamp())
                .collect::<AHashSet<_>>();

            // A THISANDFUTURE override can shift later instances back into
            // the range, so iteration continues until no shift could.
            let lookahead = overridden
                .iter()
                .filter(|((uid, _), (_, overriding))| {
                    *uid == event.uid && overriding.rid_this_and_future
                })
                .filter_map(|((_, rid), (_, overriding))| {
                    let new_start = overriding.event.as_ref()?.start.timestamp();
                    Some(rid.duration_until(new_start).abs())
                })
                .max()
                .unwrap_or(SignedDuration::ZERO);
            let stop = end.checked_add(lookahead).unwrap_or(Timestamp::MAX);

            // Set by a THISANDFUTURE override for the instances after it.
            let mut shift = None;
            let mut length = event.default_duration;

            for Candidate {
                start: original,
                end: own_end,
                ..
            } in candidates
            {
                if limit == 0 || original.timestamp() >= stop {
                    break;
                }
                match overridden.remove(&(event.uid, original.timestamp())) {
                    Some((override_comp_id, overriding)) => {
                        let Some(mut instance) = overriding.event else {
                            continue;
                        };
                        if overriding.rid_this_and_future {
                            comp_id = override_comp_id;
                            shift = Some(original.duration_until(&instance.start));
                            length = Length::exact(match &instance.end {
                                TimeOrDelta::Time(end) => instance.start.duration_until(end),
                                TimeOrDelta::Delta(delta) => *delta,
                            });
                        }
                        instance.series_comp_id = Some(series_comp_id);
                        instance.recurrence_id = overriding.rid;
                        if window.contains(&instance, overriding.overlap) {
                            limit -= 1;
                            expand.events.push(instance);
                        }
                    }
                    None if !exdates.contains(&original.timestamp()) => {
                        let start = match shift {
                            Some(shift) => original.checked_add(shift).unwrap_or(original.clone()),
                            None => original.clone(),
                        };
                        let Some(end) =
                            own_end.or_else(|| length.end_of(&start).map(TimeOrDelta::Time))
                        else {
                            continue;
                        };
                        let instance = CalendarEvent {
                            comp_id,
                            series_comp_id: Some(series_comp_id),
                            recurrence_id: Some(original),
                            start,
                            end,
                        };
                        if window.contains(&instance, event.overlap) {
                            limit -= 1;
                            expand.events.push(instance);
                        }
                    }
                    None => {}
                }
            }
        }

        // Overrides not reached by their series: those that moved an
        // instance from after the range into it, and those of malformed
        // calendars.
        for ((uid, _), (_, event)) in overridden {
            if let Some(mut cal_event) = event.event {
                cal_event.series_comp_id = series.get(&uid).copied();
                cal_event.recurrence_id = event.rid;
                if window.contains(&cal_event, event.overlap) {
                    expand.events.push(cal_event);
                }
            }
        }

        expand
    }
}

/// An instance start, and its own end if it has one (a PERIOD RDATE, or
/// DTSTART without a rule).
#[derive(Debug, Clone)]
pub(crate) struct Candidate {
    /// When the instance starts.
    pub(crate) start: Zoned,
    /// The local date-time it was generated at, when that is its identity:
    /// the rule's date-time, which in a daylight saving gap differs from the
    /// start's wall time.
    pub(crate) local: Option<jiff::civil::DateTime>,
    /// Its own end, if it has one (a PERIOD RDATE, or DTSTART without a rule).
    pub(crate) end: Option<TimeOrDelta<Zoned, SignedDuration>>,
}

/// The instances generated by an RRULE whose DTSTART is the local
/// `dt_start`, in `start_tz`.
pub(crate) fn rule_instances(
    rrule: RRule,
    dt_start: jiff::civil::DateTime,
    start_tz: Tz,
) -> Result<impl Iterator<Item = Candidate> + use<>, CalendarErrorType> {
    let floating_start = Tz::Floating
        .from_local_datetime(dt_start)
        .ok_or(CalendarErrorType::InvalidDtStart)?;
    // The rule is evaluated on local date-times, but an UNTIL in UTC (or with
    // an offset) is an instant. It is validated and iterated as its wall-clock
    // time in the series' time zone, and the resolved instances are compared
    // with the instant itself: "If the value specified by UNTIL is
    // synchronized with the specified recurrence, this DATE or DATE-TIME
    // becomes the last instance of the recurrence" (RFC 5545, Section
    // 3.3.10). A floating UNTIL is already a local date-time.
    let mut rrule = rrule;
    let mut until = None;
    if let Some(instant) = rrule
        .until
        .as_ref()
        .filter(|until| !until.time_zone().is_unknown())
        .map(Zoned::timestamp)
        && let Some(local) =
            Tz::Floating.from_local_datetime(instant.to_zoned(start_tz.to_time_zone()).datetime())
    {
        rrule.until = Some(local);
        until = Some(instant);
    }
    let mut rrule = rrule
        .validate(floating_start.clone())
        .map_err(CalendarErrorType::RRule)?;
    if until.is_some()
        && let Some(local) = &rrule.until
        && let Ok(widened) = local.checked_add(SignedDuration::from_hours(48))
    {
        // A local time in a gap resolves to a later instant, and one in a
        // fold to an earlier one, so the local bound is widened by more than
        // any UTC offset change (Samoa skipped a whole day in 2011); the
        // instants decide.
        rrule.until = Some(widened);
    }
    // The local date-times are placed in the series' time zone. A local time
    // in a gap or a fold resolves as an explicit date-time would (RFC 5545,
    // Section 3.3.5; erratum 4271).
    let resolved = RRuleIter::new(&rrule, &floating_start, true).filter_map(move |date| {
        let local = date.datetime();
        let start = if date.time_zone().is_unknown() {
            start_tz.from_local_datetime(local)?
        } else {
            date
        };
        if until.is_some_and(|until| start.timestamp() > until) {
            return None;
        }
        Some(Candidate {
            start,
            local: Some(local),
            end: None,
        })
    });
    Ok(InOrder {
        inner: resolved,
        held: None,
        shifted: std::collections::BTreeMap::new(),
    })
}

/// Keeps rule instances chronological and distinct after time zone
/// resolution. A local time in a daylight saving gap resolves past the gap
/// (02:30 becomes 03:30), after rule times that follow it locally (03:00),
/// and possibly onto one of them. Such instances wait until the rule reaches
/// their instant, and one that coincides with another instance is dropped:
/// "Duplicate instances are ignored" (RFC 5545, Section 3.8.5.3).
pub(crate) struct InOrder<I: Iterator<Item = Candidate>> {
    inner: I,
    /// The next instance at a time that exists, waiting behind earlier
    /// shifted ones.
    held: Option<Candidate>,
    /// Instances shifted past a gap, by instant.
    shifted: std::collections::BTreeMap<Timestamp, Candidate>,
}

impl<I: Iterator<Item = Candidate>> Iterator for InOrder<I> {
    type Item = Candidate;

    fn next(&mut self) -> Option<Candidate> {
        loop {
            if let Some(held) = self.held.take() {
                let instant = held.start.timestamp();
                match self.shifted.first_key_value() {
                    Some((&first, _)) if first < instant => {
                        self.held = Some(held);
                        return self.shifted.pop_first().map(|(_, shifted)| shifted);
                    }
                    Some((&first, _)) if first == instant => {
                        // The same instance; the one at an existing time stays.
                        self.shifted.pop_first();
                    }
                    _ => {}
                }
                return Some(held);
            }
            match self.inner.next() {
                Some(candidate)
                    if candidate
                        .local
                        .is_some_and(|local| local != candidate.start.datetime()) =>
                {
                    self.shifted
                        .entry(candidate.start.timestamp())
                        .or_insert(candidate);
                }
                Some(candidate) => self.held = Some(candidate),
                None => return self.shifted.pop_first().map(|(_, shifted)| shifted),
            }
        }
    }
}

/// Merges two chronological candidate streams. An instant in both is
/// generated once; an end of its own (from a PERIOD RDATE) wins.
pub(crate) struct Merge<A: Iterator<Item = Candidate>, B: Iterator<Item = Candidate>> {
    pub(crate) a: std::iter::Peekable<A>,
    pub(crate) b: std::iter::Peekable<B>,
}

impl<A: Iterator<Item = Candidate>, B: Iterator<Item = Candidate>> Iterator for Merge<A, B> {
    type Item = Candidate;

    fn next(&mut self) -> Option<Candidate> {
        let order = match (self.a.peek(), self.b.peek()) {
            (Some(a), Some(b)) => a.start.timestamp().cmp(&b.start.timestamp()),
            (Some(_), None) => std::cmp::Ordering::Less,
            (None, Some(_)) => std::cmp::Ordering::Greater,
            (None, None) => return None,
        };
        match order {
            std::cmp::Ordering::Less => self.a.next(),
            std::cmp::Ordering::Greater => self.b.next(),
            std::cmp::Ordering::Equal => {
                let a = self.a.next()?;
                let b = self.b.next()?;
                Some(Candidate {
                    start: a.start,
                    local: a.local.or(b.local),
                    end: b.end.or(a.end),
                })
            }
        }
    }
}

/// How an instance is tested against a time range (RFC 4791, Section 9.9).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Overlap {
    /// VEVENT, VJOURNAL, and VTODO with DTSTART and DUE (or no end): the
    /// half-open interval, or the instant, from start to end.
    Interval,
    /// VTODO with DTSTART and DURATION:
    /// "(start <= DTSTART+DURATION) AND ((end > DTSTART) OR (end >= DTSTART+DURATION))".
    TodoDuration,
    /// VTODO with only DUE: "(start < DUE) AND (end >= DUE)".
    TodoDue,
    /// VTODO with COMPLETED (and maybe CREATED), no DTSTART or DUE: the
    /// closed interval from CREATED, or COMPLETED, to COMPLETED.
    Closed,
    /// VTODO with only CREATED: "(end > CREATED)".
    OpenEnded,
}

#[derive(Debug, Clone, Copy)]
pub(crate) struct Window {
    pub(crate) start: Timestamp,
    pub(crate) end: Timestamp,
}

impl Window {
    pub(crate) fn contains(
        &self,
        event: &CalendarEvent<Zoned, TimeOrDelta<Zoned, SignedDuration>>,
        overlap: Overlap,
    ) -> bool {
        let start = event.start.timestamp();
        let end = match &event.end {
            TimeOrDelta::Time(time) => time.timestamp(),
            TimeOrDelta::Delta(delta) => {
                start.checked_add(*delta).unwrap_or(if delta.is_negative() {
                    Timestamp::MIN
                } else {
                    Timestamp::MAX
                })
            }
        };
        match overlap {
            Overlap::Interval if end > start => self.start < end && self.end > start,
            Overlap::Interval => self.start <= start && self.end > start,
            Overlap::TodoDuration => self.start <= end && (self.end > start || self.end >= end),
            Overlap::TodoDue => self.start < start && self.end >= start,
            Overlap::Closed => self.start <= end && self.end >= start,
            Overlap::OpenEnded => self.end > start,
        }
    }
}

#[allow(clippy::type_complexity)]
struct CalendarEventBuilder<'x> {
    event: Option<CalendarEvent<Zoned, TimeOrDelta<Zoned, SignedDuration>>>,
    dt_start: DateTimeResult,
    dt_start_tzid: Option<&'x str>,
    start_tz: Tz,
    default_duration: Length,
    rrule: Option<RRule>,
    exdates: Vec<(Option<&'x str>, DateTimeResult)>,
    rid: Option<Zoned>,
    rid_this_and_future: bool,
    overlap: Overlap,
    uid: Option<&'x str>,
    /// RDATE instances: start, and the end of a PERIOD value.
    rdates: Vec<(Zoned, Option<TimeOrDelta<Zoned, SignedDuration>>)>,
}

impl ICalendarComponent {
    #[allow(clippy::type_complexity)]
    fn build_calendar_date(
        &self,
        comp_id: u32,
        tz_resolver: &TzResolver<&'_ str>,
    ) -> Result<Option<CalendarEventBuilder<'_>>, CalendarErrorType> {
        let mut dt_start = None;
        let mut dt_start_tzid = None;
        let mut dt_start_has_time = false;
        let mut dt_end: Option<DateTimeResult> = None;
        let mut dt_end_tzid = None;
        let mut todo_dates = vec![];
        let mut rid: Option<DateTimeResult> = None;
        let mut rid_tzid = None;
        let mut rid_this_and_future = false;
        let mut duration = None;
        let mut rrule = None;
        let mut rdates = vec![];
        let mut rdates_periods = vec![];
        let mut exdates = vec![];
        let mut uid = None;

        for entry in &self.entries {
            match (&entry.name, entry.values.first()) {
                (ICalendarProperty::Uid, Some(value)) => {
                    uid = value.as_text();
                }
                (ICalendarProperty::Dtstart, Some(ICalendarValue::PartialDateTime(dt))) => {
                    dt_start = dt.to_date_time();
                    dt_start_tzid = entry.tz_id();
                    dt_start_has_time = dt.has_time();
                }
                (ICalendarProperty::Dtend, Some(ICalendarValue::PartialDateTime(dt))) => {
                    if let Some(dt) = dt.to_date_time() {
                        dt_end = Some(dt);
                        dt_end_tzid = entry.tz_id();
                    }
                }
                (
                    ICalendarProperty::Due
                    | ICalendarProperty::Completed
                    | ICalendarProperty::Created,
                    Some(ICalendarValue::PartialDateTime(dt)),
                ) if self.component_type == ICalendarComponentType::VTodo => {
                    todo_dates.push((&entry.name, dt.to_date_time(), entry.tz_id()));
                }
                (ICalendarProperty::RecurrenceId, Some(ICalendarValue::PartialDateTime(dt))) => {
                    if let Some(dt) = dt.to_date_time() {
                        for param in &entry.params {
                            match &param.name {
                                ICalendarParameterName::Tzid => {
                                    rid_tzid = param.value.as_text();
                                }
                                ICalendarParameterName::Range => {
                                    rid_this_and_future = true;
                                }
                                _ => (),
                            }
                        }

                        rid = Some(dt);
                    }
                }
                (ICalendarProperty::Duration, Some(ICalendarValue::Duration(dur))) => {
                    duration = Some(dur);
                }
                (ICalendarProperty::Rrule, Some(ICalendarValue::RecurrenceRule(rule))) => {
                    rrule = RRule::from_floating_ical(rule);
                }
                (ICalendarProperty::Rdate, _) => {
                    let tz_id = entry.tz_id();
                    for value in &entry.values {
                        match value {
                            ICalendarValue::PartialDateTime(dt) => {
                                if let Some(dt) = dt.to_date_time() {
                                    rdates.push((tz_id, dt));
                                }
                            }
                            ICalendarValue::Period(period) => match period {
                                ICalendarPeriod::Range { start, end } => {
                                    if let (Some(start), Some(end)) =
                                        (start.to_date_time(), end.to_date_time())
                                    {
                                        rdates_periods.push((tz_id, start, TimeOrDelta::Time(end)));
                                    }
                                }
                                ICalendarPeriod::Duration { start, duration } => {
                                    if let Some(start) = start.to_date_time() {
                                        rdates_periods.push((
                                            tz_id,
                                            start,
                                            TimeOrDelta::Delta(Length::of(duration)),
                                        ));
                                    }
                                }
                            },
                            _ => (),
                        }
                    }
                }
                (ICalendarProperty::Exdate, _) => {
                    let tz_id = entry.tz_id();
                    for value in &entry.values {
                        if let ICalendarValue::PartialDateTime(dt) = value
                            && let Some(dt) = dt.to_date_time()
                        {
                            exdates.push((tz_id, dt));
                        }
                    }
                }
                _ => (),
            }
        }

        let mut overlap = if self.component_type == ICalendarComponentType::VTodo
            && dt_start.is_some()
            && duration.is_some()
        {
            Overlap::TodoDuration
        } else {
            Overlap::Interval
        };
        let dt_start = match dt_start {
            Some(dt_start) => dt_start,
            None => match &rid {
                Some(rid) => {
                    dt_start_tzid = rid_tzid;
                    rid.clone()
                }
                None => match self.component_type {
                    ICalendarComponentType::VEvent => {
                        return Err(CalendarErrorType::MissingDtStart);
                    }
                    ICalendarComponentType::VTodo => {
                        let mut due_idx = None;
                        let mut completed_idx = None;
                        let mut created_idx = None;

                        for (idx, (prop, dt, _)) in todo_dates.iter().enumerate() {
                            if dt.is_some() {
                                match prop {
                                    ICalendarProperty::Due => due_idx = Some(idx),
                                    ICalendarProperty::Completed => completed_idx = Some(idx),
                                    ICalendarProperty::Created => created_idx = Some(idx),
                                    _ => (),
                                }
                            }
                        }

                        match (due_idx, completed_idx, created_idx) {
                            (Some(due_idx), _, _) => {
                                overlap = Overlap::TodoDue;
                                let due = &mut todo_dates[due_idx];
                                dt_start_tzid = due.2;
                                dt_start_has_time = true;
                                due.1.take().unwrap()
                            }
                            (_, Some(completed_idx), Some(created_idx)) => {
                                overlap = Overlap::Closed;
                                let completed = &mut todo_dates[completed_idx];
                                dt_end = completed.1.take();
                                dt_end_tzid = completed.2;

                                let created = &mut todo_dates[created_idx];
                                dt_start_tzid = created.2;
                                created.1.take().unwrap()
                            }
                            (_, Some(date_idx), _) | (_, _, Some(date_idx)) => {
                                overlap = if completed_idx.is_some() {
                                    Overlap::Closed
                                } else {
                                    Overlap::OpenEnded
                                };
                                let date = &mut todo_dates[date_idx];
                                dt_start_tzid = date.2;
                                dt_start_has_time = true;
                                date.1.take().unwrap()
                            }
                            _ => {
                                return Ok(None);
                            }
                        }
                    }
                    _ => {
                        return Ok(None);
                    }
                },
            },
        };
        let event;
        // A DTSTART in UTC (or with an offset) recurs in UTC, not in the
        // default time zone (RFC 5545, Section 3.3.5).
        let start_tz = dt_start
            .tz()
            .unwrap_or_else(|| tz_resolver.resolve_or_default(dt_start_tzid));
        let dt_start_tz = dt_start
            .to_date_time_with_tz(start_tz)
            .ok_or(CalendarErrorType::InvalidDtStart)?;
        let default_duration = if let Some(dt_end) = dt_end {
            let end = dt_end
                .to_date_time_with_tz(tz_resolver.resolve_or_default(dt_end_tzid.or(dt_start_tzid)))
                .ok_or(CalendarErrorType::InvalidDtEnd)?;

            // Every instance lasts "the same exact duration" as DTSTART to
            // DTEND (RFC 5545, Section 3.8.5.3), across time zones and
            // daylight saving changes. Between dates, days are nominal.
            let length = if dt_start_has_time {
                Length::exact(dt_start_tz.duration_until(&end))
            } else {
                Length::between_dates(dt_start.date_time, dt_end.date_time)
            };
            event = Some(CalendarEvent::new(
                comp_id,
                dt_start_tz,
                TimeOrDelta::Time(end),
            ));
            length
        } else if let Some(duration) = duration {
            let length = Length::of(duration);
            let end = length
                .end_of(&dt_start_tz)
                .ok_or(CalendarErrorType::InvalidDuration)?;
            event = Some(CalendarEvent::new(
                comp_id,
                dt_start_tz,
                TimeOrDelta::Time(end),
            ));
            length
        } else if let Some((due, due_tzid)) = todo_dates
            .into_iter()
            .filter_map(|(prop, dt, tz_id)| {
                if prop == &ICalendarProperty::Due {
                    dt.map(|dt| (dt, tz_id))
                } else {
                    None
                }
            })
            .next()
        {
            let end = due
                .to_date_time_with_tz(tz_resolver.resolve_or_default(due_tzid.or(dt_start_tzid)))
                .ok_or(CalendarErrorType::InvalidDtEnd)?;

            // Every instance lasts "the same exact duration" as DTSTART to
            // DUE (RFC 5545, Section 3.8.5.3), across time zones and
            // daylight saving changes. Between dates, days are nominal.
            let length = if dt_start_has_time {
                Length::exact(dt_start_tz.duration_until(&end))
            } else {
                Length::between_dates(dt_start.date_time, due.date_time)
            };
            event = Some(CalendarEvent::new(
                comp_id,
                dt_start_tz,
                TimeOrDelta::Time(end),
            ));
            length
        } else {
            /*
               For cases where a "VEVENT" calendar component
               specifies a "DTSTART" property with a DATE value type but no
               "DTEND" nor "DURATION" property, the event's duration is taken to
               be one day.  For cases where a "VEVENT" calendar component
               specifies a "DTSTART" property with a DATE-TIME value type but no
               "DTEND" property, the event ends on the same calendar date and
               time of day specified by the "DTSTART" property.
            */

            /*
               RFC 4791, Section 9.9 states the same as a number: the duration
               is 0 seconds for a DATE-TIME DTSTART and 1 day (+P1D) for a DATE.
            */
            let length = if dt_start_has_time {
                Length::ZERO
            } else {
                Length::ONE_DAY
            };
            let end = length
                .end_of(&dt_start_tz)
                .ok_or(CalendarErrorType::InvalidDtStart)?;
            event = Some(CalendarEvent::new(
                comp_id,
                dt_start_tz,
                TimeOrDelta::Time(end),
            ));
            length
        };
        let rid = if let Some(rid) = rid {
            rid.to_date_time_with_tz(tz_resolver.resolve_or_default(rid_tzid.or(dt_start_tzid)))
        } else {
            None
        };

        // RDATE instances, in the order they occur.
        let mut rdate_instances = Vec::with_capacity(rdates.len() + rdates_periods.len());
        for (tz_id, rdate) in rdates {
            if let Some(date_start) =
                rdate.to_date_time_with_tz(tz_resolver.resolve_or_default(tz_id.or(dt_start_tzid)))
            {
                rdate_instances.push((date_start, None));
            }
        }
        for (tz_id, start, end) in rdates_periods {
            let tz = tz_resolver.resolve_or_default(tz_id.or(dt_start_tzid));
            let Some(date_start) = start.to_date_time_with_tz(tz) else {
                continue;
            };
            let date_end = match end {
                TimeOrDelta::Time(end) => end.to_date_time_with_tz(tz),
                TimeOrDelta::Delta(length) => length.end_of(&date_start),
            };
            if let Some(date_end) = date_end {
                rdate_instances.push((date_start, Some(TimeOrDelta::Time(date_end))));
            }
        }
        rdate_instances.sort_by_key(|(start, _)| start.timestamp());

        Ok(Some(CalendarEventBuilder {
            event,
            dt_start_tzid,
            default_duration,
            rrule,
            exdates,
            start_tz,
            dt_start,
            rid,
            rid_this_and_future,
            overlap,
            uid,
            rdates: rdate_instances,
        }))
    }
}

impl TimeOrDelta<DateTimeResult, SignedDuration> {
    pub fn into_date_time_with_tz(self, tz: Tz) -> Option<TimeOrDelta<Zoned, SignedDuration>> {
        match self {
            TimeOrDelta::Time(time) => time.to_date_time_with_tz(tz).map(TimeOrDelta::Time),
            TimeOrDelta::Delta(delta) => Some(TimeOrDelta::Delta(delta)),
        }
    }
}

impl CalendarEvent<Zoned, TimeOrDelta<Zoned, SignedDuration>> {
    pub fn timestamps(&self) -> (i64, i64) {
        let timestamp = self.start.timestamp().as_second();
        let end_timestamp = match &self.end {
            TimeOrDelta::Time(time) => time.timestamp().as_second(),
            TimeOrDelta::Delta(delta) => timestamp + delta.as_secs(),
        };

        (timestamp, end_timestamp)
    }

    pub fn try_into_date_time(self) -> Option<CalendarEvent<Zoned, Zoned>> {
        match self.end {
            TimeOrDelta::Time(time) => Some(time),
            // An exact duration (RFC 5545, Section 3.3.6), as in `timestamps`.
            TimeOrDelta::Delta(delta) => self.start.checked_add(delta).ok(),
        }
        .map(|end| CalendarEvent {
            comp_id: self.comp_id,
            series_comp_id: self.series_comp_id,
            recurrence_id: self.recurrence_id,
            start: self.start,
            end,
        })
    }
}

impl Display for CalendarErrorType {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        match self {
            CalendarErrorType::MissingDtStart => write!(f, "Missing DTSTART property"),
            CalendarErrorType::InvalidDtStart => write!(f, "Invalid DTSTART property"),
            CalendarErrorType::InvalidDtEnd => write!(f, "Invalid DTEND property"),
            CalendarErrorType::InvalidDuration => write!(f, "Invalid DURATION property"),
            CalendarErrorType::RRule(err) => write!(f, "RRule error: {err}"),
        }
    }
}
